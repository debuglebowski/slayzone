import { Command } from 'commander'

/**
 * Shell completions, generated from the CLI's own command tree — so a new command
 * (or subcommand) completes without anyone remembering to list it here. Covers
 * top-level commands and their direct subcommands, with descriptions.
 */

interface Entry {
  name: string
  description: string
  subs: Array<{ name: string; description: string }>
  /** Option flags (long form), offered where a command has no subcommands. */
  flags: string[]
}

const SHELLS = ['fish', 'zsh', 'bash'] as const

function visible(cmd: Command): Command[] {
  return cmd.commands.filter((c) => !(c as unknown as { _hidden?: boolean })._hidden)
}

function entries(root: Command): Entry[] {
  return visible(root).map((c) => ({
    name: c.name(),
    description: c.description().split('\n')[0],
    subs: visible(c).map((s) => ({ name: s.name(), description: s.description().split('\n')[0] })),
    flags: c.options.map((o) => o.long).filter((l): l is string => typeof l === 'string')
  }))
}

/** Inside single quotes: fish escapes `'` as `\'`, zsh/bash close-escape-reopen. */
const fishQ = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
const shQ = (s: string) => `'${s.replace(/'/g, "'\\''")}'`
const zshDesc = (name: string, description: string) =>
  shQ(`${name.replace(/:/g, '\\:')}:${description}`)

export function fishScript(root: Command): string {
  const lines = [
    '# slay fish completions — generated by: slay completions fish',
    'complete -c slay -f'
  ]
  const all = entries(root)
  for (const e of all)
    lines.push(
      `complete -c slay -n '__fish_use_subcommand' -a ${fishQ(e.name)} -d ${fishQ(e.description)}`
    )
  for (const e of all) {
    const words = e.name === 'completions' ? [...SHELLS] : e.subs.map((s) => s.name)
    if (words.length)
      lines.push(
        `complete -c slay -n '__fish_seen_subcommand_from ${e.name}' -a ${fishQ(words.join(' '))}`
      )
  }
  return `${lines.join('\n')}\n`
}

export function zshScript(root: Command): string {
  const all = entries(root)
  const ident = (name: string) => `${name.replace(/[^a-zA-Z0-9]/g, '_')}_commands`
  const out = [
    '# slay zsh completions — generated by: slay completions zsh',
    '# Add to ~/.zshrc: eval "$(slay completions zsh)"',
    '_slay() {',
    '  local -a commands',
    '  commands=(',
    ...all.map((e) => `    ${zshDesc(e.name, e.description)}`),
    '  )'
  ]
  for (const e of all) {
    if (!e.subs.length) continue
    out.push(`  local -a ${ident(e.name)}`, `  ${ident(e.name)}=(`)
    for (const s of e.subs) out.push(`    ${zshDesc(s.name, s.description)}`)
    out.push('  )')
  }
  out.push('  case $words[2] in')
  for (const e of all) {
    if (e.name === 'completions') {
      out.push('    completions)', `      _arguments ':shell:(${SHELLS.join(' ')})'`, '      ;;')
    } else if (e.subs.length) {
      out.push(
        `    ${e.name})`,
        `      _describe ${shQ(`${e.name} commands`)} ${ident(e.name)}`,
        '      ;;'
      )
    } else if (e.flags.length) {
      out.push(
        `    ${e.name})`,
        `      _arguments ${e.flags.map((f) => shQ(f)).join(' ')}`,
        '      ;;'
      )
    }
  }
  out.push(
    '    *)',
    "      _describe 'slay commands' commands",
    '      ;;',
    '  esac',
    '}',
    'compdef _slay slay'
  )
  return `${out.join('\n')}\n`
}

export function bashScript(root: Command): string {
  const all = entries(root)
  const out = [
    '# slay bash completions — generated by: slay completions bash',
    '# Add to ~/.bashrc: eval "$(slay completions bash)"',
    '_slay_completions() {',
    '  local cur prev',
    '  cur="${COMP_WORDS[COMP_CWORD]}"',
    '  prev="${COMP_WORDS[COMP_CWORD-1]}"',
    '  if [ $COMP_CWORD -eq 1 ]; then',
    `    COMPREPLY=( $(compgen -W "${all.map((e) => e.name).join(' ')}" -- "$cur") )`,
    '  elif [ $COMP_CWORD -eq 2 ]; then',
    '    case "$prev" in'
  ]
  for (const e of all) {
    const words =
      e.name === 'completions' ? [...SHELLS] : e.subs.length ? e.subs.map((s) => s.name) : e.flags
    if (!words.length) continue
    out.push(
      `      ${e.name})`,
      `        COMPREPLY=( $(compgen -W "${words.join(' ')}" -- "$cur") )`,
      '        ;;'
    )
  }
  out.push('    esac', '  fi', '}', 'complete -F _slay_completions slay')
  return `${out.join('\n')}\n`
}

/** `root`: the program, read when the command runs (every command is registered by then). */
export function completionsCommand(root: () => Command): Command {
  const cmd = new Command('completions')
    .argument('<shell>', 'Shell to generate completions for: fish | zsh | bash')
    .description('Print shell completion script')
    .action((shell: string) => {
      switch (shell) {
        case 'fish':
          process.stdout.write(fishScript(root()))
          console.error('# Install: slay completions fish > ~/.config/fish/completions/slay.fish')
          break
        case 'zsh':
          process.stdout.write(zshScript(root()))
          console.error('# Install: eval "$(slay completions zsh)"  (add to ~/.zshrc)')
          break
        case 'bash':
          process.stdout.write(bashScript(root()))
          console.error('# Install: eval "$(slay completions bash)"  (add to ~/.bashrc)')
          break
        default:
          console.error(`Unknown shell: ${shell}. Supported: fish, zsh, bash`)
          process.exit(1)
      }
    })
  return cmd
}
