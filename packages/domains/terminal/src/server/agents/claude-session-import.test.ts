/**
 * Chat A (plan 3.6 / 3.10): a resumed or handed-over conversation's history,
 * from the CLI's session-file records to the chat's events.
 */
import { expect, test } from 'vitest'
import { claudeSessionHistory } from './claude-session-import'

const user = (uuid: string, content: unknown, extra: Record<string, unknown> = {}) => ({
  type: 'user',
  uuid,
  message: { role: 'user', content },
  ...extra
})
const assistant = (uuid: string, block: Record<string, unknown>) => ({
  type: 'assistant',
  uuid,
  message: { id: `msg_${uuid}`, role: 'assistant', model: 'claude-haiku-5-5', content: [block] }
})

test('user messages, replies, tool calls and results become the chat history', () => {
  const events = claudeSessionHistory([
    user('u1', 'run ls'),
    assistant('a1', { type: 'thinking', thinking: 'hm', signature: 's' }),
    assistant('a2', { type: 'tool_use', id: 'tu1', name: 'Bash', input: { command: 'ls' } }),
    user('r1', [{ type: 'tool_result', tool_use_id: 'tu1', content: 'a.txt' }], {
      toolUseResult: { stdout: 'a.txt' }
    }),
    assistant('a3', { type: 'text', text: 'one file' }),
    user('u2', [{ type: 'text', text: 'thanks' }])
  ])
  expect(events).toEqual([
    { kind: 'user-message', id: 'u1', text: 'run ls', history: true },
    expect.objectContaining({ kind: 'assistant-thinking', uuid: 'a1', text: 'hm' }),
    expect.objectContaining({ kind: 'tool-call', id: 'tu1', name: 'Bash', uuid: 'a2' }),
    expect.objectContaining({
      kind: 'tool-result',
      toolUseId: 'tu1',
      structured: { stdout: 'a.txt' }
    }),
    expect.objectContaining({ kind: 'assistant-text', text: 'one file', uuid: 'a3' }),
    { kind: 'user-message', id: 'u2', text: 'thanks', history: true }
  ])
})

test('the CLI’s own records stay out: meta, compaction summaries, slash-command echoes, interrupts', () => {
  const events = claudeSessionHistory([
    user(
      'm1',
      'Caveat: the messages below were generated by the user while running local commands.',
      {
        isMeta: true
      }
    ),
    user('c1', 'This session is being continued from a previous conversation…', {
      isCompactSummary: true
    }),
    user('s1', '<command-name>/compact</command-name>'),
    user('i1', [{ type: 'text', text: '[Request interrupted by user]' }]),
    user('u1', 'real one')
  ])
  expect(events).toEqual([{ kind: 'user-message', id: 'u1', text: 'real one', history: true }])
})

test('a compaction boundary is kept', () => {
  const events = claudeSessionHistory([
    {
      type: 'system',
      subtype: 'compact_boundary',
      uuid: 'b1',
      compact_metadata: { trigger: 'manual', pre_tokens: 100 }
    }
  ])
  expect(events).toEqual([expect.objectContaining({ kind: 'compact-boundary', trigger: 'manual' })])
})
