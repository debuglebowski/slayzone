/**
 * Which tRPC procedures, REST routes and MCP tools need a hub ADMIN account (T-15).
 *
 * WHY THIS EXISTS: on a hub that requires login every account has a role, `admin`
 * or `user` (hub-auth `user.role`, carried on every principal). The admin runs the
 * hub: accounts, computers, hub-wide settings. A user does their own work. Until
 * this, nothing but `/api/hub/users` read the role, so any signed-in account could
 * mint enrollment tokens, edit automations that run on the hub, restore a backup or
 * rename the hub.
 *
 * SAME SHAPE AS `scopes.ts`, for the same reasons (read its docstring): one explicit
 * flat map per surface, cross-checked against the LIVE router, route table and tool
 * list in `admin-policy.test.ts`. A procedure, route or tool added without a decision
 * fails CI by name, and one that is somehow unclassified at runtime is refused to a
 * non-admin (fail closed). No router imports here, deliberately.
 *
 * THE VOCABULARY:
 *   admin — a non-admin account is refused: tRPC `FORBIDDEN`, REST 403, MCP tool
 *           error, each carrying the stable code {@link ADMIN_ONLY}, plus one
 *           `authz.denied` audit line.
 *   user  — any signed-in account. A few `user` items need the admin role for SOME
 *           inputs only; they are listed in {@link CONDITIONAL_ADMIN} and checked in
 *           the handler, with the same code and audit line.
 *   open  — reachable with no session at all on a hub that requires login.
 *           DESCRIPTIVE ONLY: no gate admits anything because it is `open` here.
 *           Openness comes from `openProcedure` (tRPC) and `AUTH_BOOTSTRAP_PATHS`
 *           (REST, apps/hub `rest-auth.ts`); the tests assert this map matches them,
 *           so marking an item `open` cannot open it.
 *
 * ORTHOGONAL TO `scopes.ts`. A scope says what a CREDENTIAL CLASS may reach (a
 * browser session vs the desktop app); the role says what the ACCOUNT may do. A call
 * passes both.
 *
 * INERT WITHOUT LOGIN. On a hub that does not require login (the desktop app's own
 * hub: `SLAYZONE_HUB_REQUIRE_LOGIN=0`) there is no principal and nothing here is
 * consulted, so the desktop keeps full access exactly as before.
 *
 * ADMIN IS MANAGEMENT, NEVER A READ PATH (O-4). The admin role only gates ACTIONS; it
 * never widens what a caller may see of another user's sessions, prompts, files or
 * computers. The one place the role widens a view, `computers.list`, shows management
 * metadata only (see `computers/server/visibility.ts`).
 *
 * Ownership (whose project, task or session) is NOT decided here: T-17..T-19. It is
 * decided for `admin` items too (T-106): an admin automation call on another user's
 * project answers not-found, like any user's would.
 *
 * @module transport/server/admin-policy
 */
import type { PrincipalRole } from './context'

export type AccessClass = 'admin' | 'user' | 'open'

/** The stable refusal code, on every surface. */
export const ADMIN_ONLY = 'ADMIN_ONLY'

/**
 * Whether an account with `role` may call an item of class `cls`. An admin may call
 * anything. `undefined` (unclassified) needs an admin: fail closed.
 */
export function roleAllows(cls: AccessClass | undefined, role: PrincipalRole): boolean {
  if (role === 'admin') return true
  return cls === 'user' || cls === 'open'
}

