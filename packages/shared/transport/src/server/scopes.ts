/**
 * Resolve the minimum scope a path requires. `undefined` (path not in the
 * policy) is treated as `never` by the caller (`trpc.ts`) — this function
 * itself does not special-case that, so the caller's fail-closed behavior is
 * visible at the call site rather than hidden in here.
 */
export function requiredScope(path: string): ProcedureScope | undefined {
  return SCOPE_POLICY[path]
}

/**
 * Whether a principal holding `scopes` may call `path`. `full` always passes
 * (skips the policy entirely — every existing client stays byte-identical).
 * An unclassified path (not in `SCOPE_POLICY`) is refused — `scopes.test.ts`
 * asserts no live path is ever in that state.
 */
export function isPathAllowed(scopes: readonly Scope[], path: string): boolean {
  if (scopes.includes('full')) return true
  const required = requiredScope(path)
  if (required === undefined || required === 'never') return false
  return scopes.includes(required)
}
