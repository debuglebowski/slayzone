/**
 * Capability scopes for the tRPC API — what a session class other than `full`
 * may reach.
 *
 * WHY THIS EXISTS: exposing a web UI means a browser session that is NOT the
 * desktop app, NOT the CLI, and NOT a co-located `slay` — reached over the
 * internet, holding a weaker credential than everything that exists today. A
 * scoped session must not be able to read provider API keys, execute arbitrary
 * shell commands, touch the filesystem sandbox, or mint a computer credential,
 * even while it CAN type into an already-running agent (the actual product).
 *
 * THIS FILE IS A SECURITY DOCUMENT, not just data. A reviewer should be able to
 * read `SCOPE_POLICY` top to bottom and know exactly what the web can do. Keep
 * entries grouped by router, keep the router-level comments, and do not let this
 * rot into a diff nobody reads.
 *
 * WHY AN EXPLICIT ALLOWLIST, NOT `.meta()` OR PER-ROUTER DEFAULTS:
 *   - `.meta()` is typed `TMeta | undefined` — an un-annotated procedure yields
 *     `undefined`, which can be MADE to deny at runtime, but nothing forces a
 *     new procedure to carry `.meta()` at authoring time. The failure is
 *     invisible until the UI 403s in production.
 *   - Per-router defaults don't work here: `pty` alone spans `onData` (must be
 *     readable) and `create` (must never be reachable), so you end up with
 *     per-procedure overrides inside the router anyway, with extra indirection.
 *   - An explicit flat map, cross-checked against the live router in
 *     `scopes.test.ts`, gives fail-closed TWICE: an unknown path is `FORBIDDEN`
 *     at runtime (see `trpc.ts`), and a procedure added without being classified
 *     fails CI by name (`scopes.test.ts`'s exhaustiveness check). That second
 *     property is the one `.meta()` cannot give — nothing else in this codebase
 *     forces a future PR to make a security decision before merging.
 *
 * NO ROUTER IMPORTS HERE, deliberately. This file must stay pure data + the
 * vocabulary comments — `scopes.test.ts` is where the coupling to the live
 * `appRouter` happens, in a test, not in production code.
 *
 * @module transport/server/scopes
 */

/**
 * The scope vocabulary. Kept deliberately tiny — a large vocabulary rots.
 *
 *   full  — everything that exists today: the desktop app, the CLI, and any
 *           session resolved via `verifySession` (a real better-auth session,
 *           reached by a bearer or the bootstrap-owner token). A `full`
 *           principal SKIPS the scope check entirely (see `trpc.ts`), so every
 *           existing client is byte-identical to before scopes existed.
 *   read  — observe-only queries and subscriptions. No mutation of any kind.
 *   tasks — task / project / tag / artifact / terminal-tab CRUD. The
 *           collaborative surface a web user actually edits.
 *   agent — speak to an ALREADY-RUNNING agent session (type into it, read its
 *           output, adjust its runtime settings). Explicitly NOT "choose what
 *           runs" — see the honest-statement block below.
 */
export type Scope = 'full' | 'read' | 'tasks' | 'agent'

/**
 * Every scope a principal may hold. `full` implies every other scope (checked
 * first in the gate, see `trpc.ts`), so a `full` principal never needs the
 * other three listed — but a scoped (non-`full`) principal's `scopes` array may
 * list more than one, e.g. `['read', 'tasks', 'agent']` for a typical web login.
 */
export type PrincipalScope = Scope

/**
 * A procedure's classification — every {@link Scope} PLUS `never`. `never` is
 * not something a principal can hold; it exists only as a policy VALUE, so a
 * procedure can be explicitly marked unreachable by any scoped session rather
 * than merely absent from the map (see `SCOPE_POLICY`'s docstring for why that
 * distinction is load-bearing for the exhaustiveness test).
 */
export type ProcedureScope = Scope | 'never'

/**
 * Per-procedure minimum admitting scope, keyed by the SAME dotted path
 * `appRouter._def.procedures` uses (`<router>.<procedure>`, nested routers
 * flatten fully — e.g. `chat.queue.clear`).
 *
 * `never` is a DELIBERATE entry, not an absence — it is what lets
 * `scopes.test.ts` assert every live path was actually considered, rather than
 * merely "not yet granted". A path missing from this map entirely is refused by
 * the runtime gate (fail-closed) AND fails the exhaustiveness test (fail-loud) —
 * see `trpc.ts` and `scopes.test.ts`.
 *
 * ── pty: "speak to an existing session", never "choose what runs" ──────────
 * Granted (`agent`): write/submit/interrupt/resize/touch, every read
 * (getBuffer*, exists, list, getState, sessionList, sessionGetState, chatList,
 * clearBuffer, ackEnsureAlive) and every `on*` subscription.
 * Denied (`never`): `create` (takes `anyInput` — an UNVALIDATED spawn spec, not
 * admitted even narrowed), `kill`, `setShellOverride`, `setTheme`,
 * `validate`, `warmSetProjectTabCounts`, every `modes*` procedure, and every
 * `test*` procedure.
 *
 * WRITTEN DOWN, NOT DISCOVERED LATER: `pty.onData` (and `chat.onEvent`) can now
 * take an optional `sessionIds`/`tabIds` filter (routers/pty.ts, routers/chat.ts)
 * that drops non-matching events server-side — but the filter is OPT-IN. A
 * caller (any caller, any scope, `agent` included) that subscribes with no
 * filter still receives every byte of every live session on the hub, exactly
 * as before the filter existed. So `agent`/`read` granting this subscription is
 * necessarily a grant to "every terminal on the hub" until the WEB CLIENT
 * itself always passes `sessionIds` scoped to what that session's user may
 * see — the scope system has no way to enforce that from the server side,
 * since the filter is a bandwidth optimization, not an authorization boundary.
 *
 * ── chat: the same split, applied to its own create-shaped procedures ──────
 * `start` / `reset` / `abortAndPop` all take `chatCreateOpts` — an
 * attacker-chosen `mode` + `cwd` (+ optional provider-flag override) that
 * either creates a fresh session or re-creates one with different parameters.
 * That is the identical risk class to `pty.create`, so all three are `never`
 * despite chat otherwise being granted wholesale. `kill` / `remove` take only a
 * `tabId` (no mode/cwd choice) but are denied FOR SYMMETRY with `pty.kill`:
 * ending the host process is reserved for `full`; steering the agent already
 * running in it is what `agent` scope is for. Runtime-setting changes on an
 * existing session (`setMode`, `setModel`, `setEffort`, `setFastMode`,
 * `setCollaboration`) stay granted — no cwd/binary choice involved.
 *
 * ── computers: visibility-filtered reads only ───────────────────────────────
 * `list` / `resolveTaskComputer` / `onStatusChange` are granted as `read` — a
 * web client cannot render a task without showing which computer it runs on,
 * and these are filtered in the STORE by `computers/server/visibility.ts`
 * before scopes ever see them, so a scoped session sees exactly what its user
 * may see. Every mutation is `never`, INCLUDING `setTaskComputer` /
 * `setProjectDefaultComputer` — binding a task to a computer is choosing WHERE
 * CODE RUNS (`visibility.ts` calls this out explicitly as code execution in
 * that account), which is a materially different action from watching and
 * steering an agent that is already placed.
 *
 * ── granted wholesale (the collaborative CRUD surface) ─────────────────────
 * `task.*`, `projects.*`, `projectGroups.*`, `tags.*`, `artifacts.*`,
 * `taskTerminals.*` → `tasks`. `chat.*` (minus the five denials above) → `agent`.
 * `agentPrompts.list/onChanged`, `agentSessions.list/onChanged`,
 * `agentTurns.list/onChanged`, `history.*`, `usageAnalytics.*`,
 * `agentLifecycle.onEvent`, `notify.onTasksChanged` → `read`.
 * `task.testRecordPendingSpawn` is carved out to `never` (a test hook, not part
 * of the CRUD surface it happens to live in).
 *
 * ── granted narrowly (theme) ─────────────────────────────────────────────────
 * `settings.getEffectiveTheme` / `getThemeSource` / `onThemeChanged` /
 * `setTheme` → `read`. A browser needs to render the correct light/dark theme;
 * the rest of `settings.*` (an arbitrary KV store of unknown scope) is `never`.
 *
 * ── denied wholesale (infra, danger, or simply out of Phase-1 scope) ───────
 * Every procedure in `app` (native window/browser-panel/floating-agent/webview
 * control — nothing here is meaningful from a browser tab), `aiConfig`
 * (provider API keys), `integrations` (credential-store backed), `worktrees`
 * (git mutations + `mergeWithAI`/`analyzeConflict`), `processes`, `automations`,
 * `menu`, `workspace` (includes `setAllowedRoots` — mutates the fs sandbox
 * itself), `fileEditor` (raw filesystem writes), `testPanel`, `diagnostics`,
 * `feedback`, `notify` (minus the one exception above), `telemetry`, `template`,
 * `hub` (minus `describe`, which is reachable regardless — see below).
 *
 * `hub.describe` is built on `openProcedure` (see `trpc.ts`), so it never
 * reaches the scope gate at all — it is listed here as `read` only so the
 * exhaustiveness test has an entry for every live path, not because the value
 * is ever consulted for it.
 */
