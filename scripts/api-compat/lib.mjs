/**
 * Pure parts of scripts/check-api-compat.mjs (the client ↔ hub API compatibility
 * check): which release to compare with, the generated type-level comparison, reading
 * tsgo's verdict, and the policy that turns breaks into pass/fail. No IO here.
 */

/** Stable release tags only (`v0.43.0`, not `v0.36.0-beta.1`): what users run. */
export const RELEASE_TAG = /^v(\d+)\.(\d+)\.(\d+)$/

function versionKey(tag) {
  const m = RELEASE_TAG.exec(tag)
  return m ? [Number(m[1]), Number(m[2]), Number(m[3])] : null
}

/**
 * The release to compare with: the newest stable tag that is not HEAD itself — the
 * release whose clients and hubs this code will meet first. `tags`: [{ tag, sha }].
 */
export function pickBaseTag(tags, headSha) {
  const stable = tags
    .map((t) => ({ ...t, key: versionKey(t.tag) }))
    .filter((t) => t.key && t.sha !== headSha)
    .sort((a, b) => b.key[0] - a.key[0] || b.key[1] - a.key[1] || b.key[2] - a.key[2])
  return stable[0]?.tag ?? null
}

/**
 * The contract constants of an `api-version.ts` source. A release from before the
 * contract has no such file: `null` source = API 0, both minimums 0.
 */
export function parseContract(source) {
  if (source == null) return { HUB_API_VERSION: 0, MIN_CLIENT_API: 0, MIN_HUB_API: 0 }
  const read = (name) => {
    const m = new RegExp(`export const ${name} = (\\d+)\\b`).exec(source)
    if (!m) throw new Error(`api-version.ts: no \`export const ${name} = <integer>\``)
    return Number(m[1])
  }
  return {
    HUB_API_VERSION: read('HUB_API_VERSION'),
    MIN_CLIENT_API: read('MIN_CLIENT_API'),
    MIN_HUB_API: read('MIN_HUB_API')
  }
}

/** The categories the generated file reports, in the order its assertions appear. */
export const CATEGORIES = ['removed', 'added', 'oldClient', 'newClient', 'droppedInput']

/**
 * The type-level comparison of two `AppRouter`s. Each category is asserted to be
 * `never`; tsgo (run with `noErrorTruncation`) prints the paths of every one that is
 * not, as a union of string literals — the only way to read a computed type out of
 * tsgo, which has no compiler API.
 *
 *  - removed:      procedures the base had and HEAD lacks (an older client calls them).
 *  - added:        procedures HEAD has and the base lacks (a newer client calling one
 *                  on an older hub gets NOT_FOUND).
 *  - oldClient:    an older client against a newer hub: its input must be accepted
 *                  (old input ⊆ new input) and the hub's output readable by it
 *                  (new output ⊆ old output).
 *  - newClient:    a newer client against an older hub: the reverse.
 *  - droppedInput: input fields a newer client sends that an older hub's zod object
 *                  strips silently (the input type checks, the data is lost).
 */
export function checkSource({ newRouter, oldRouter }) {
  const lines = [
    '// Generated by scripts/check-api-compat.mjs — do not edit.',
    `import type { AppRouter as NewRouter } from ${JSON.stringify(newRouter)}`,
    `import type { AppRouter as OldRouter } from ${JSON.stringify(oldRouter)}`,
    '',
    'type Proc = { _def: { type: unknown; $types: { input: unknown; output: unknown } } }',
    'type RecOf<T> = T extends { _def: { record: infer R } } ? R : T',
    // `T extends object ?` forces evaluation; without it tsgo leaves some nested
    // routers' paths deferred (and they print as an unevaluated `Paths<…>`).
    "type Paths<T, P extends string = ''> = T extends object",
    '  ? {',
    '      [K in keyof T & string]-?: T[K] extends infer V',
    '        ? V extends Proc',
    '          ? `${P}${K}`',
    '          : Paths<RecOf<V>, `${P}${K}.`>',
    '        : never',
    '    }[keyof T & string]',
    '  : never',
    'type At<T, Path extends string> = Path extends `${infer H}.${infer R}`',
    '  ? H extends keyof T',
    '    ? At<RecOf<T[H]>, R>',
    '    : never',
    '  : Path extends keyof T',
    '    ? T[Path]',
    '    : never',
    'type N = RecOf<NewRouter>',
    'type O = RecOf<OldRouter>',
    'type NP = Paths<N>',
    'type OP = Paths<O>',
    'type Common = NP & OP',
    'type Sub<A, B> = [A] extends [B] ? true : false',
    // What crosses the wire, compared instead of the declared types: a type-only brand
    // (`string & { [BrandSymbol]: 'VersionId' }`) is a `unique symbol` that differs
    // between the two source trees, so it would read as a break where nothing changed.
    // Symbol keys never cross the wire (superjson drops them); a branded primitive is
    // its primitive. Literals stay literals; arrays lose readonly-ness only.
    'type Prim = string | number | boolean | bigint | symbol | null | undefined | void',
    'type Opaque = Date | RegExp | Uint8Array | Map<unknown, unknown> | Set<unknown> | ((...a: never[]) => unknown)',
    'type Wire<T> = T extends Prim',
    '  ? Exclude<keyof T, keyof Primitive<T>> extends never',
    '    ? T',
    '    : Primitive<T>',
    '  : T extends Opaque',
    '    ? T',
    '    : T extends AsyncIterable<infer U>',
    '      ? AsyncIterable<Wire<U>>',
    '      : T extends readonly (infer E)[]',
    '        ? Wire<E>[]',
    '        : { [K in keyof T as K extends symbol ? never : K]: Wire<T[K]> }',
    'type Primitive<T> = T extends string ? string : T extends number ? number : T extends boolean ? boolean : T extends bigint ? bigint : T',
    "type Types<R, P extends string> = At<R, P> extends infer X extends Proc ? X['_def']['$types'] : never",
    "type In<R, P extends string> = Wire<Types<R, P>['input']>",
    "type Out<R, P extends string> = Wire<Types<R, P>['output']>",
    'type OldClient<P extends string> = Sub<In<O, P>, In<N, P>> extends false',
    '  ? `${P} input`',
    '  : Sub<Out<N, P>, Out<O, P>> extends false',
    '    ? `${P} output`',
    '    : never',
    'type NewClient<P extends string> = Sub<In<N, P>, In<O, P>> extends false',
    '  ? `${P} input`',
    '  : Sub<Out<O, P>, Out<N, P>> extends false',
    '    ? `${P} output`',
    '    : never',
    'type Keys<T> = T extends readonly unknown[] ? never : T extends object ? keyof T & string : never',
    // Only where the input otherwise type-checks (an incompatible input is already
    // `newClient`, and a field it adds is not a SILENT loss there), and only for a
    // single object type: for a union, which member an older hub's schema matches —
    // and so which fields it strips — is not knowable from the types.
    'type IsUnion<T, U = T> = T extends unknown ? ([U] extends [T] ? false : true) : never',
    'type Dropped<P extends string> = Sub<In<N, P>, In<O, P>> extends true',
    '  ? true extends IsUnion<NonNullable<In<N, P>>> | IsUnion<NonNullable<In<O, P>>>',
    '    ? never',
    '    : Keys<NonNullable<In<O, P>>> extends never',
    '      ? never',
    '      : `${P} input.${Exclude<Keys<NonNullable<In<N, P>>>, Keys<NonNullable<In<O, P>>>>}`',
    '  : never',
    'type Each<F extends "oldClient" | "newClient" | "droppedInput"> = Common extends infer P extends string',
    '  ? P extends unknown',
    '    ? F extends "oldClient" ? OldClient<P> : F extends "newClient" ? NewClient<P> : Dropped<P>',
    '    : never',
    '  : never',
    "type None = '__none__'",
    ''
  ]
  const prelude = lines.length
  const exprs = {
    removed: 'Exclude<OP, NP>',
    added: 'Exclude<NP, OP>',
    oldClient: 'Each<"oldClient">',
    newClient: 'Each<"newClient">',
    droppedInput: 'Each<"droppedInput">'
  }
  const lineOf = {}
  for (const cat of CATEGORIES) {
    // The template literal makes tsgo print the literals, not the alias name.
    lines.push(`export const ${cat}: None = null as unknown as \`\${${exprs[cat]}}\``)
    lineOf[cat] = lines.length
  }
  return { source: `${lines.join('\n')}\n`, lineOf, prelude: lines.slice(0, prelude) }
}

/**
 * One assignment per break that tsgo explains when it fails: the side that must be
 * assignable to the other, so its diagnostic says which field and why. `breaks`:
 * `{ oldClient: string[], newClient: string[] }` as `evaluate` reports them.
 */
export function explainSource(prelude, breaks) {
  const lines = [...prelude]
  const lineOf = {}
  const pair = (dir, kind) =>
    dir === 'oldClient'
      ? kind === 'input'
        ? ['In<N, P>', 'In<O, P>']
        : ['Out<O, P>', 'Out<N, P>']
      : kind === 'input'
        ? ['In<O, P>', 'In<N, P>']
        : ['Out<N, P>', 'Out<O, P>']
  let n = 0
  for (const dir of ['oldClient', 'newClient']) {
    for (const b of breaks[dir]) {
      const m = /^(\S+) (input|output)$/.exec(b)
      if (!m) continue
      const [target, source] = pair(dir, m[2]).map((t) => t.replace('P', JSON.stringify(m[1])))
      lines.push(`export const explain${n++}: ${target} = null as unknown as ${source}`)
      lineOf[lines.length] = `${dir}: ${b}`
    }
  }
  return { source: `${lines.join('\n')}\n`, lineOf }
}

/**
 * Read tsgo's output for the generated file. Returns `{ found, unexpected }`: the
 * paths per category, and any diagnostic in the generated file that is not one of
 * its five assertions (or one whose type is not a union of literals — `string`
 * means something degraded to `any`, and the comparison cannot be trusted).
 */
export function parseVerdict(output, checkFile, lineOf) {
  const found = Object.fromEntries(CATEGORIES.map((c) => [c, []]))
  const unexpected = []
  const byLine = new Map(Object.entries(lineOf).map(([cat, line]) => [line, cat]))
  const at = new RegExp(
    `^${checkFile.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\((\\d+),\\d+\\): (.*)$`
  )
  for (const raw of output.split('\n')) {
    const m = at.exec(raw.trim())
    if (!m) continue
    const cat = byLine.get(Number(m[1]))
    const assertion = /^error TS2322: Type '(.*)' is not assignable to type '"__none__"'\.$/.exec(
      m[2]
    )
    if (!cat || !assertion || !/^"/.test(assertion[1])) {
      unexpected.push(raw.trim())
      continue
    }
    found[cat] = [...assertion[1].matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((x) => x[1]).sort()
  }
  return { found, unexpected }
}

/**
 * Turn the breaks into a verdict.
 *
 * Every break is a direction: `oldClient` (an older client meets this hub — removed,
 * oldClient) or `newClient` (this client meets an older hub — added, newClient,
 * droppedInput).
 * A break is covered when the contract excludes that pairing — `MIN_CLIENT_API` (resp.
 * `MIN_HUB_API`) above the base's API version, so the pair refuses each other with a
 * clear message instead of failing call by call — or when `acks` records it with the
 * reason it is accepted. Anything else is a violation.
 */
export function evaluate({ found, base, head, acks }) {
  const errors = []
  if (head.MIN_CLIENT_API > head.HUB_API_VERSION)
    errors.push('MIN_CLIENT_API is above HUB_API_VERSION: a hub would refuse its own app')
  if (head.MIN_HUB_API > head.HUB_API_VERSION)
    errors.push('MIN_HUB_API is above HUB_API_VERSION: the app would refuse its own hub')
  if (head.HUB_API_VERSION < base.HUB_API_VERSION)
    errors.push(`HUB_API_VERSION went down (${base.HUB_API_VERSION} → ${head.HUB_API_VERSION})`)

  const breaks = {
    oldClient: [...found.removed.map((p) => `${p} removed`), ...found.oldClient],
    // A procedure this client calls that an older hub lacks fails NOT_FOUND there —
    // unless the client gates it (`hubHasFeature`), which is what acknowledging says.
    newClient: [
      ...found.added.map((p) => `${p} added`),
      ...found.newClient,
      ...found.droppedInput.map((p) => `${p} dropped`)
    ]
  }
  const covered = {
    oldClient: head.MIN_CLIENT_API > base.HUB_API_VERSION,
    newClient: head.MIN_HUB_API > base.HUB_API_VERSION
  }
  const violations = { oldClient: [], newClient: [] }
  const acked = { oldClient: [], newClient: [] }
  for (const dir of ['oldClient', 'newClient']) {
    for (const b of breaks[dir]) {
      if (covered[dir]) continue
      if (typeof acks?.[dir]?.[b] === 'string' && acks[dir][b].trim()) acked[dir].push(b)
      else violations[dir].push(b)
    }
  }
  const stale = { oldClient: [], newClient: [] }
  for (const dir of ['oldClient', 'newClient']) {
    for (const key of Object.keys(acks?.[dir] ?? {})) {
      if (covered[dir] || !breaks[dir].includes(key)) stale[dir].push(key)
    }
  }
  const ok = errors.length === 0 && violations.oldClient.length + violations.newClient.length === 0
  return { ok, errors, breaks, covered, violations, acked, stale }
}

/** `acks` without the stale entries (`--prune`). */
export function pruneAcks(acks, stale) {
  const out = { ...acks }
  for (const dir of ['oldClient', 'newClient']) {
    if (!acks?.[dir]) continue
    out[dir] = Object.fromEntries(
      Object.entries(acks[dir]).filter(([k]) => !stale[dir].includes(k))
    )
  }
  return out
}
